class _YamlRenderer:
    """YAML-form renderer: ``.yaml`` files with ``.py`` / ``.sql`` sidecars."""

    suffix = ".yaml"

    def render(self, kind: str, stem: str, doc: dict[str, Any]) -> str:
        """Render *doc* as a canonically-ordered YAML document.

        Args:
            kind: The spec kind, selecting the ordering helper.
            stem: Unused (YAML files bind by document, not variable name).
            doc: The authoring-format spec dict.

        Returns:
            The YAML document text.
        """
        del stem
        if kind == "Entity":
            body = doc
        elif kind == "FeatureGroup":
            body = _ordered_fg_doc(doc)
        elif kind in _FV_APPLIED_KINDS:
            body = _ordered_fv_doc(doc)
        else:
            body = _ordered_ds_doc(doc)
        return yaml.dump(body, default_flow_style=False, sort_keys=False)

    def write(self, path: Path, content: str, warnings: list[str]) -> bool:
        """Write *content* to *path* unconditionally.

        Args:
            path: Destination ``.yaml`` path.
            content: YAML body.
            warnings: Unused (the YAML path never skips a write).

        Returns:
            Always ``True``.
        """
        del warnings
        path.write_text(content)
        return True

    def check_stem(self, stem: str, warnings: list[str]) -> bool:
        """Accept any stem (YAML filenames need no Python-identifier check).

        Args:
            stem: Unused.
            warnings: Unused.

        Returns:
            Always ``True``.
        """
        del stem, warnings
        return True

    def fv_sidecar(self, fv_doc: dict[str, Any], fv_dir: Path, stem: str) -> str | None:
        """Externalise the FV UDF body to a sibling ``.py`` sidecar.

        Args:
            fv_doc: The FV authoring dict (mutated to reference the sidecar).
            fv_dir: The ``feature_views`` output directory.
            stem: The FV file stem.

        Returns:
            The sidecar path, or ``None`` if the FV has no UDF.
        """
        return _extract_udf_to_py_file(fv_doc, fv_dir, stem)

    def ds_sidecar(self, ds_spec: dict[str, Any], ds_dir: Path, stem: str) -> str | None:
        """Externalise a datasource query to a sibling ``.sql`` sidecar.

        Args:
            ds_spec: The datasource authoring dict (mutated to reference it).
            ds_dir: The ``datasources`` output directory.
            stem: The datasource file stem.

        Returns:
            The sidecar path, or ``None`` if the datasource has no inline query.
        """
        return _extract_query_to_sql_file(ds_spec, ds_dir, stem)


